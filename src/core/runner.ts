/** Carry-over chains are restarted after this many cases so one agent conversation does not grow without bound. */
const MAX_CARRY_CHAIN = 5;
const normStep = (s: string) => s.toLowerCase().replace(/\s+/g, " ").replace(/[.\s]+$/, "").trim();
/** Number of leading steps two cases have in common (case- and whitespace-insensitive). */
export function sharedPrefix(a: string[], b: string[]): number {
  let n = 0;
  while (n < a.length && n < b.length - 1 && normStep(a[n]) === normStep(b[n])) n++; // always leave at least one step to run
  return n;
}

/**
 * Splits a suite into work units for the worker pool. Consecutive cases that share opening steps form a chain
 * (carry-over needs them in order on one browser), but a chain is capped so one long run of similar cases cannot
 * pin the whole suite to a single worker. Longest chains go first so the slowest one does not start last.
 */
export function planChains(cases: TestCase[], workers: number, continuity: "continue" | "fresh"): TestCase[][] {
  if (workers <= 1) return cases.length ? [cases] : [];
  const cap = Math.max(1, Math.min(MAX_CARRY_CHAIN, Math.ceil(cases.length / workers)));
  const chains: TestCase[][] = [];
  for (const tc of cases) {
    const last = chains[chains.length - 1];
    const joins = last && continuity === "continue" && last.length < cap && sharedPrefix(last[last.length - 1].steps, tc.steps) > 0;
    if (joins) last.push(tc);
    else chains.push([tc]);
  }
  return chains.sort((a, b) => b.length - a.length); // stable: equal-length chains keep suite order
}

