export async function runSuite(
  suite: TestSuite,
  org: OrgConfig,
  opts: RunOptions & { toolRoot: string },
  emit: (e: RunEvent) => void,
  abort = new AbortController(),
): Promise<CaseResult[]> {
  const log = (message: string) => emit({ type: "log", message });
  const toolDir = path.join(opts.workspaceDir, ".sf-ai-tester");
  fs.mkdirSync(toolDir, { recursive: true });
  // Session cookies and run output must never be committed.
  fs.writeFileSync(path.join(toolDir, ".gitignore"), "*\n");

  const needsAutomation = suite.cases.some((c) => (c.mode ?? opts.mode) !== "manual");
  if (needsAutomation) ensureAutomationProject(opts.workspaceDir, log);

  // Log in to the org only when some case actually targets Salesforce; web-only runs never touch the org.
  const targets = new Map(suite.cases.map((tc) => [tc.id, resolveTarget(tc, suite)] as const));
  const sfCount = [...targets.values()].filter((t) => t === "salesforce").length;
  if (sfCount < suite.cases.length) log(`${suite.cases.length - sfCount} web case(s) (no Salesforce)${sfCount ? `, ${sfCount} Salesforce case(s)` : " - skipping the org login"}.`);
  const auth: AuthSession = sfCount
    ? await authenticate(org, path.join(toolDir, "auth"), opts.login, {
        log,
        needsUser: (message) => emit({ type: "needsUser", message }),
      })
    : blankSession(toolDir, suite.baseUrl);

  const runDir = path.join(toolDir, "runs", new Date().toISOString().replace(/[:.]/g, "-"));
  fs.mkdirSync(runDir, { recursive: true });
  const results: CaseResult[] = [];
  const continuity = opts.continuity ?? "continue";
  const startHost = (log: (m: string) => void) =>
    startBrowserHost({ storageStatePath: auth.storageStatePath, headless: opts.headless }).catch((e) => {
      log(`  (shared browser unavailable: ${(e as Error).message} - each agent session will open its own browser)`);
      return undefined;
    });

  // Work units (see planChains). With one worker everything is a single chain, so continuity spans the whole run.
  const workers = Math.max(1, Math.min(4, opts.workers ?? 1));
  const queue = planChains(suite.cases, workers, continuity);
  const poolSize = Math.min(workers, queue.length);
  if (poolSize > 1) log(`Running ${suite.cases.length} case(s) on ${poolSize} parallel workers (${queue.length} chain(s)).`);
  // Chains are claimed in order; a worker that pre-starts an agent for the next chain reserves it. Other workers take
  // unreserved chains first and a reserved one only when nothing else is left, so warm starts never cost parallelism.
  const claimed = new Set<number>();
  const reservedBy = new Map<number, number>();
  const claim = (w: number) => {
    const open = queue.map((_, i) => i).filter((i) => !claimed.has(i));
    const i = open.find((j) => (reservedBy.get(j) ?? w) === w) ?? open[0];
    if (i !== undefined) claimed.add(i);
    return i;
  };
  /** Reserves the next chain no worker has claimed or reserved, for this worker's pre-started agent. */
  const reserveNext = (w: number) => {
    const i = queue.findIndex((_, j) => !claimed.has(j) && !reservedBy.has(j));
    if (i < 0) return undefined;
    reservedBy.set(i, w);
    return i;
  };

  const finish = (result: CaseResult, tc: TestCase, log: (m: string) => void) => {
    delete result.recorded;
    delete result.specGreen;
    result.caseHash = caseHash(tc);
    log(`=== ${tc.id} [${result.mode}] ${result.status.toUpperCase()} (${result.model}): ${result.summary}`);
    results.push(result);
    emit({ type: "caseEnd", result, runDir });
    writeRun(runDir, suite, org, auth, results);
  };

  const models = opts.models.length ? opts.models : [""];
  const recordings = new Recordings(path.join(toolDir, "recordings", slug(suite.name)));
  const modesOf = (tc: TestCase): ("manual" | "automation")[] => {
    const mode = tc.mode ?? opts.mode;
    return mode === "both" ? ["manual", "automation"] : [mode];
  };
  const evidenceFor = (tc: TestCase, m: string) => {
    const dir = path.join(runDir, "evidence", `${tc.id}-${m}`);
    fs.mkdirSync(dir, { recursive: true });
    return dir;
  };
  /** Agent settings for one case; a pre-started agent must be created from the same values it later runs with. */
  const agentCtx = (tc: TestCase, evidenceDir: string, model: string, host: BrowserHost | undefined, log: (m: string) => void): AgentContext => ({
    suite,
    auth,
    workspaceDir: opts.workspaceDir,
    toolRoot: opts.toolRoot,
    evidenceDir,
    headless: opts.headless,
    model,
    maxTurns: opts.maxTurns,
    useSubscription: opts.useSubscription,
    abort,
    log,
    cdpEndpoint: host?.cdpEndpoint,
    orgContext: targets.get(tc.id) === "salesforce" ? opts.orgContext?.(tc) : undefined,
    target: targets.get(tc.id),
    baseUrl: suite.baseUrl,
  });
  const recordingFor = (tc: TestCase, m: string) => (m === "manual" && opts.replayManual !== false ? recordings.get(tc) : undefined);

  /** One worker: its own browser (in continue mode) and carry-over state, pulling chains off the shared queue. */
  const worker = async (w: number) => {
    const log = (msg: string) => emit({ type: "log", message: poolSize > 1 ? msg.replace(/^(\n?)/, `$1[W${w}] `) : msg });
    // "continue": one browser for everything this worker runs - no closing/reopening/re-login between cases.
    const runHost: BrowserHost | undefined = continuity === "continue" ? await startHost(log) : undefined;
    /** Last manual agent session on this browser - the next case can pick it up if its opening steps match. */
    let lastManual: { tc: TestCase; sessionId: string; status: string; chain: number } | undefined;
    /** Case that last drove this browser (any mode), for the "browser continues from" note. */
    let lastOnBrowser: string | undefined;
    /** Agent process already starting for the next task, so it is ready when the current one ends. */
    let pending: { key: string; warm: Promise<WarmQuery | undefined> } | undefined;
    const discard = (warm?: Promise<WarmQuery | undefined>) => void warm?.then((q) => q?.close(), () => undefined);

    const tasksOf = (chain: TestCase[]) => chain.flatMap((tc) => modesOf(tc).map((m) => ({ tc, m })));
    try {
      for (let c = claim(w); c !== undefined && !abort.signal.aborted; c = claim(w)) {
        const list = tasksOf(queue[c]);
        for (let k = 0; k < list.length && !abort.signal.aborted; k++) {
          const { tc, m } = list[k];
          // Next task: the rest of this chain, else the head of a chain reserved for this worker (an idle worker
          // may still take it if nothing else is left; the pre-started agent is then simply discarded).
          const reserved = k + 1 < list.length ? undefined : reserveNext(w);
          const upcoming = list[k + 1] ?? (reserved !== undefined ? tasksOf(queue[reserved])[0] : undefined);
          const key = `${tc.id}:${m}`;
          let warm = pending?.key === key ? pending.warm : undefined;
          if (pending && !warm) discard(pending.warm);
          pending = undefined;

          // Pre-start the next task's agent now. Only a fresh session on the run-long browser can use one: a replayed
          // automation spec needs no agent, and a carried-over case resumes the previous session instead.
          if (upcoming && runHost && !abort.signal.aborted) {
            const u = upcoming;
            const replays = u.m === "automation" && !!opts.replay?.(u.tc);
            const mayCarry = u.m === "manual" && m === "manual" && sharedPrefix(tc.steps, u.tc.steps) > 0 && !recordingFor(u.tc, u.m);
            if (!replays && !mayCarry) {
              const warmCtx = agentCtx(u.tc, evidenceFor(u.tc, u.m), models[0], runHost, log);
              pending = {
                key: `${u.tc.id}:${u.m}`,
                warm: prewarmAgent(u.tc, u.m, warmCtx).catch((e) => {
                  log(`  (could not pre-start the agent for ${u.tc.id}: ${(e as Error).message})`);
                  return undefined;
                }),
              };
            }
          }

          const evidenceDir = evidenceFor(tc, m);

          // Automation re-run: replay the passing spec this case already has - plain Playwright, no AI.
          const replayFile = m === "automation" ? opts.replay?.(tc) : undefined;
          let replayFailure: AgentContext["replayFailure"];
          let announced = false;
          if (replayFile) {
            emit({ type: "caseStart", id: tc.id, title: tc.title, mode: m, model: "replay" });
            announced = true;
            const rp = await replaySpec(tc, replayFile, opts.workspaceDir, auth, log, evidenceDir);
            if (rp.passed) {
              discard(warm);
              finish(rp.passed, tc, log);
              continue;
            }
            replayFailure = { specFile: replayFile, output: rp.failure ?? "" };
            log(`>>> ${tc.id} replayed spec failed - handing it to the AI to heal the script or confirm a defect`);
          }

          const attempts: NonNullable<CaseResult["attempts"]> = [];
          let result!: CaseResult;
          // The browser for this case: the worker's run-long one, or (fresh mode) one shared by this case's
          // model attempts so an escalation still continues on the page the previous model left off.
          const host = runHost ?? (await startHost(log));
          const ownsHost = !runHost;
          const started = Date.now();
          let extraCost = 0;

          try {
            // Manual re-run with a recording of the last pass: replay its browser actions at Playwright speed, then the
            // AI only checks the expected results. Anything short of a confirmed pass runs the case in full below.
            const rec = host ? recordingFor(tc, m) : undefined;
            let replayedHere = false;
            if (rec && host) {
              emit({ type: "caseStart", id: tc.id, title: tc.title, mode: m, model: "replay" });
              announced = true;
              log(`\n=== ${tc.id} [manual] ${tc.title} - replaying ${rec.actions.length} recorded action(s) from ${rec.recordedAt.slice(0, 10)}`);
              const rp = await replayRecording(rec, host);
              replayedHere = true;
              lastOnBrowser = key;
              if (rp.ok) {
                log(`  replayed in ${rp.seconds}s - asking ${models[0] || "the default model"} to check the expected results`);
                const verify = await runCaseWithAgent(tc, m, {
                  ...agentCtx(tc, evidenceDir, models[0], host, log),
                  warm,
                  verifyReplay: { actions: rec.actions.length, seconds: rp.seconds },
                });
                warm = undefined;
                verify.model = models[0] || "default";
                attempts.push({ model: `replay + ${verify.model}`, status: verify.status, summary: verify.summary, trail: verify.trail });
                if (verify.status === "passed") {
                  lastManual = undefined; // the steps were not done in this conversation, so there is nothing to carry over
                  const summary = `Replayed ${rec.actions.length} recorded actions in ${rp.seconds}s; AI checked the results: ${verify.summary}`;
                  finish({ ...verify, summary, attempts, durationMs: Date.now() - started }, tc, log);
                  continue;
                }
                extraCost += verify.costUsd;
                log(`>>> ${tc.id} check after replay was ${verify.status} - running the case in full with the AI to confirm`);
              } else {
                recordings.remove(tc); // the recorded flow no longer works; a passing full run records a new one
                log(`>>> ${tc.id} replay stopped at ${rp.error} - running the case with the AI`);
              }
            }

            // Same opening steps as the previous manual case on this browser? Carry its session over and skip them.
            let carryOver: AgentContext["carryOver"];
            let resume: AgentContext["resume"];
            if (continuity === "continue" && host && m === "manual" && !replayedHere && lastManual && lastOnBrowser === `${lastManual.tc.id}:manual`) {
              const shared = sharedPrefix(lastManual.tc.steps, tc.steps);
              if (shared > 0 && lastManual.status !== "error" && lastManual.chain < MAX_CARRY_CHAIN) {
                carryOver = { fromCase: lastManual.tc.id, sharedSteps: shared, prevStatus: lastManual.status };
                resume = { sessionId: lastManual.sessionId, model: "", status: lastManual.status, summary: "" };
                log(`>>> ${tc.id} continues from ${lastManual.tc.id}: steps 1-${shared} are the same and already done in this browser`);
              }
            }
            const browserContinues = continuity === "continue" && host && lastOnBrowser && !carryOver ? lastOnBrowser.split(":")[0] : undefined;
            // Where the browser was when this case started: a recording replays from here.
            const startUrl = host && !carryOver ? (await host.page()).url() : undefined;
            const recorded: string[] = [];
            let recordable = m === "manual" && !carryOver;

            for (let i = 0; i < models.length; i++) {
              const model = models[i];
              if (i === 0 && !announced) emit({ type: "caseStart", id: tc.id, title: tc.title, mode: m, model });
              log(`\n=== ${tc.id} [${m}] ${tc.title}${model ? ` (model: ${model})` : ""}${i > 0 && resume ? " - continuing previous session" : ""}`);
              result = await runCaseWithAgent(tc, m, {
                ...agentCtx(tc, evidenceDir, model, host, log),
                warm: i === 0 ? warm : undefined,
                resume,
                carryOver: i === 0 ? carryOver : undefined,
                browserContinues: i === 0 ? browserContinues : undefined,
                replayFailure: i === 0 ? replayFailure : undefined,
              });
              warm = undefined;
              lastOnBrowser = key;
              if (result.recorded) recorded.push(...result.recorded);
              else recordable = false;
              if (m === "automation" && result.status === "passed") {
                // The agent's own last run of the unchanged spec is a real Playwright run - no need to repeat it.
                result = result.specGreen
                  ? { ...result, summary: `${result.summary} (verified: its final Playwright run passed)` }
                  : await verifySpec(result, opts.workspaceDir, auth, log, evidenceDir);
              }
              result.model = model || "default";
              attempts.push({ model: result.model, status: result.status, summary: result.summary, trail: result.trail });
              const next = models[i + 1];
              if (result.status === "passed" || !next || abort.signal.aborted) break;
              // Hand over: the next model resumes this conversation (and, with the shared browser, this page).
              resume = result.sessionId ? { sessionId: result.sessionId, model: result.model, status: result.status, summary: result.summary } : undefined;
              if (!resume || !host) recordable = false; // a fresh restart: the earlier actions are not part of one flow
              const how = resume ? (host ? "continuing on the same page and session" : "continuing the same session") : "starting fresh";
              const reason = `${model || "default"} reported ${result.status}: ${result.summary.slice(0, 200)}`;
              log(`>>> Escalating ${tc.id} [${m}] to ${next} (${how}) - ${reason}`);
              emit({ type: "escalate", id: tc.id, mode: m, from: model, to: next, reason });
            }

            if (recordable && host && result.status === "passed" && recorded.length) {
              recordings.save(tc, { startUrl, actions: recorded, model: result.model });
              log(`  recorded ${recorded.length} browser action(s) - the next manual run replays them instead of the AI driving`);
            }
            if (m === "manual") {
              lastManual = result.sessionId
                ? { tc, sessionId: result.sessionId, status: result.status, chain: carryOver ? (lastManual?.chain ?? 0) + 1 : 1 }
                : undefined;
            }
          } finally {
            discard(warm);
            if (ownsHost) await host?.close();
          }
          result.attempts = attempts;
          result.costUsd += extraCost;
          result.durationMs = Date.now() - started;
          finish(result, tc, log);
        }
      }
    } finally {
      discard(pending?.warm);
      await runHost?.close();
    }
  };

  await Promise.all(Array.from({ length: Math.max(1, poolSize) }, (_, i) => worker(i + 1)));

  // AI analyst: one pass over all failures, grouped by root cause, with next steps.
  if (opts.analyze !== false && !abort.signal.aborted && results.some((r) => r.status !== "passed")) {
    const model = opts.models[opts.models.length - 1];
    log(`\n>>> AI analyst reviewing ${results.filter((r) => r.status !== "passed").length} failure(s) with ${model || "the default model"}...`);
    try {
      const analysis = await analyzeRun(suite, results, { model, useSubscription: opts.useSubscription, workspaceDir: opts.workspaceDir, abort });
      if (analysis) {
        fs.writeFileSync(path.join(runDir, "analysis.json"), JSON.stringify(analysis, null, 2));
        log(`>>> AI analysis: ${analysis.headline}`);
        emit({ type: "analysis", runDir, analysis });
      }
    } catch (e) {
      log(`  (AI analysis skipped: ${(e as Error).message})`);
    }
  }

  const reportPath = writeRun(runDir, suite, org, auth, results);
  log(`\nReport: ${reportPath}`);
  emit({ type: "runEnd", runDir, results });
  return results;
}

function writeRun(runDir: string, suite: TestSuite, org: OrgConfig, auth: AuthSession, results: CaseResult[]) {
  fs.writeFileSync(path.join(runDir, "results.json"), JSON.stringify({ suite: suite.name, org: org.name, results }, null, 2));
  return writeReport(runDir, suite.name, `${org.name} (${auth.instanceUrl})`, results);
}

function ensureAutomationProject(workspaceDir: string, log: (m: string) => void) {
  if (!fs.existsSync(path.join(workspaceDir, "node_modules", "@playwright", "test"))) {
    throw new Error(
      `Automation mode needs @playwright/test in ${workspaceDir}. Run "npm i -D @playwright/test" there ` +
        `(or the "SF AI Tester: Initialize Test Project" command), or use manual mode.`,
    );
  }
  const cfg = path.join(workspaceDir, PW_CONFIG);
  if (!fs.existsSync(cfg)) {
    fs.writeFileSync(cfg, PW_CONFIG_TEMPLATE);
    log(`Created ${PW_CONFIG}`);
  } else {
    // Configs this tool generated earlier used a small fixed viewport; upgrade them (user-written configs are left alone).
    const cur = fs.readFileSync(cfg, "utf8");
    if (cur.includes("Generated by SF AI Tester") && cur.includes("width: 1440, height: 900")) {
      fs.writeFileSync(cfg, cur.replace("width: 1440, height: 900", "width: 1920, height: 1080"));
      log(`Updated ${PW_CONFIG} viewport to 1920x1080`);
    }
    const now = fs.readFileSync(cfg, "utf8");
    const fixedOut = "outputDir: './.sf-ai-tester/playwright-output',";
    if (now.includes("Generated by SF AI Tester") && now.includes(fixedOut)) {
      fs.writeFileSync(cfg, now.replace(fixedOut, "outputDir: process.env.SF_PW_OUTPUT_DIR || './.sf-ai-tester/playwright-output',"));
      log(`Updated ${PW_CONFIG} so parallel workers do not share one output folder`);
    }
  }
  fs.mkdirSync(path.join(workspaceDir, SPEC_DIR), { recursive: true });
}

/** Re-runs the generated spec outside the agent so a "passed" verdict is backed by a real green run. */
/** Session for runs without Salesforce: an empty browser state, base URL as the "instance". */
function blankSession(toolDir: string, baseUrl?: string): AuthSession {
  const dir = path.join(toolDir, "auth");
  fs.mkdirSync(dir, { recursive: true });
  const storageStatePath = path.join(dir, "blank.storage.json");
  fs.writeFileSync(storageStatePath, JSON.stringify({ cookies: [], origins: [] }));
  return { storageStatePath, instanceUrl: baseUrl ?? "about:blank" };
}

/** Per-case Playwright output (traces, failure screenshots), so parallel spec runs never empty each other's folder. */
export const pwOutputDir = (evidenceDir: string) => path.join(evidenceDir, "playwright");

/** Runs one generated spec with plain Playwright (no AI). Returns the exit code and the tail of its output. */
async function runSpec(specFile: string, workspaceDir: string, auth: AuthSession, log: (m: string) => void, evidenceDir: string) {
  let output = "";
  const started = Date.now();
  const code = await new Promise<number>((resolve) => {
    const child = spawn("npx", ["playwright", "test", "--config", PW_CONFIG, specFile], {
      cwd: workspaceDir,
      shell: process.platform === "win32",
      env: { ...process.env, SF_INSTANCE_URL: auth.instanceUrl, SF_STORAGE_STATE: auth.storageStatePath, SF_PW_OUTPUT_DIR: pwOutputDir(evidenceDir) },
    });
    const take = (d: Buffer) => {
      const s = String(d);
      output = (output + s).slice(-6000);
      log(`  | ${s.trimEnd()}`);
    };
    child.stdout.on("data", take);
    child.stderr.on("data", take);
    child.on("close", (c) => resolve(c ?? 1));
    child.on("error", () => resolve(1));
  });
  return { code, output, ms: Date.now() - started };
}

/** Fingerprint of what a case tests: a stored spec is only replayed while this is unchanged. */
export function caseHash(tc: TestCase): string {
  const body = JSON.stringify([tc.title, tc.preconditions ?? [], tc.steps, tc.expected, tc.data ?? null]);
  return createHash("sha1").update(body).digest("hex").slice(0, 16);
}

/**
 * Automation re-run without AI: execute the passing spec this case already has. Returns a passed result,
 * or the failure output so the agent can heal the script or confirm a defect.
 */
async function replaySpec(tc: TestCase, specFile: string, workspaceDir: string, auth: AuthSession, log: (m: string) => void, evidenceDir: string) {
  log(`\n=== ${tc.id} [automation] ${tc.title} - replaying ${specFile} (no AI)`);
  const run = await runSpec(specFile, workspaceDir, auth, log, evidenceDir);
  if (run.code !== 0) return { passed: undefined, failure: run.output };
  const passed: CaseResult = {
    id: tc.id,
    title: tc.title,
    mode: "automation",
    status: "passed",
    summary: `Replayed ${specFile} with Playwright - passed in ${Math.round(run.ms / 1000)}s, no AI needed.`,
    steps: tc.steps.map((step) => ({ step, status: "passed" as const, actual: "Covered by the replayed spec." })),
    defects: [],
    evidence: [],
    specFile,
    durationMs: run.ms,
    costUsd: 0,
    turns: 0,
    model: "replay",
  };
  return { passed, failure: undefined };
}

async function verifySpec(
  result: CaseResult,
  workspaceDir: string,
  auth: AuthSession,
  log: (m: string) => void,
  evidenceDir: string,
): Promise<CaseResult> {
  if (!result.specFile || !fs.existsSync(path.join(workspaceDir, result.specFile))) {
    return { ...result, status: "error", summary: `Agent reported pass but spec file is missing: ${result.specFile}` };
  }
  log(`  verifying ${result.specFile} with an independent run...`);
  const { code } = await runSpec(result.specFile, workspaceDir, auth, log, evidenceDir);
  if (code === 0) return { ...result, summary: `${result.summary} (verified by independent re-run)` };
  return {
    ...result,
    status: "failed",
    summary: `${result.summary} — BUT the independent re-run failed (flaky or environment-dependent script).`,
    defects: [
      ...result.defects,
      { title: "Generated spec is not stable", severity: "minor", details: `${result.specFile} passed for the agent but failed on re-run.` },
    ],
  };
}
